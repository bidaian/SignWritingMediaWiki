namespace Sgnw\Core\Regex;

/**
 * Convert a regex with capturing groups into a non-capturing equivalent.
 *
 * @param string $pattern
 * @return string
 */
function non_capturing($pattern)
{
    return preg_replace('/\((?!\?)/', '(?:', $pattern);
}

